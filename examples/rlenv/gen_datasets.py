"""Generate DATASETS.md from the artifacts, so every number in it is readable back to a file.

One row per shard, built from that shard's own GEN-REPORT.json plus the lane's measurement JSONs. The
point of publishing it this way is that a consumer (STARVLA) should not have to ask what a shard can
support: the two pixel numbers say how much of the image the goal controls, the necessity numbers say how
much of the score is earnable only by reading the goal, and the dwell numbers say what the success label
means. A shard whose headroom is small is not broken, but no goal ablation measured on it is informative.

Usage: python examples/rlenv/gen_datasets.py --data ~/svla-rlenv-data --runs <lane>/runs --out DATASETS.md
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import time


def load(p):
    try:
        return json.load(open(p))
    except Exception:
        return None


def _emb():
    # this script runs from the harness repo, not from the pinned strands_vla worktree, so the import that
    # every other script gets via --svla has to be made explicitly here (it failed exactly once, loudly).
    import sys
    for p in (os.path.expanduser("~/rlenv-svla-pin"), os.path.expanduser("~/svla-lonely-electron")):
        if p not in sys.path and os.path.isdir(p):
            sys.path.insert(0, p)
    from strands_vla.embodiments import EMBODIMENTS as EMB
    return EMB


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--data", default=os.path.expanduser("~/svla-rlenv-data"))
    p.add_argument("--runs", default=os.path.expanduser(
        "~/.tiny/strands-vla-20261009/lanes/RLENV/runs"))
    p.add_argument("--out", required=True)
    a = p.parse_args(argv)

    shards = []
    for d in sorted(glob.glob(os.path.join(a.data, "*"))):
        r = load(os.path.join(d, "GEN-REPORT.json"))
        if r:
            shards.append((os.path.basename(d), r))

    nec = {os.path.basename(f).replace("necessity-", "").replace(".json", ""): load(f)
           for f in glob.glob(os.path.join(a.runs, "necessity-*.json"))}
    dwl = {os.path.basename(f).replace("dwell-", "").replace(".json", ""): load(f)
           for f in glob.glob(os.path.join(a.runs, "dwell-*.json"))}
    pix = load(os.path.join(a.runs, "contrast.json")) or {}
    pp = (load(os.path.join(a.runs, "price-push.json")) or {}).get("arms") or {}
    cr = (load(os.path.join(a.runs, "capture-radius.json")) or {}).get("arms") or {}
    lbs = {os.path.basename(f).replace("loadback-", "").replace(".json", ""): load(f)
           for f in glob.glob(os.path.join(a.runs, "loadback-*.json"))}
    vgs = {os.path.basename(f).replace("verify-goals-", "").replace(".json", ""): load(f)
           for f in glob.glob(os.path.join(a.runs, "verify-goals-*.json"))}

    L = []
    w = L.append
    classes: list = []
    horizons: list = []
    w("# RLENV shards — what each one can and cannot support")
    w("")
    w("Generated by `examples/rlenv/gen_datasets.py` from each shard's own `GEN-REPORT.json` and the lane's")
    w("measurement JSONs. Nothing here is typed by hand; regenerate after any harvest.")
    w("")
    w(f"Generated {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}. Scene code pinned at the")
    w("`strands-vla` sha recorded in each report; generator commits are in `robots-rlenv`.")
    w("")
    w("## Shards")
    w("")
    w("| shard | class | episodes | keep | band / horizon | goals sidecar | load-back | criterion floor | "
      "validated ceiling | what was discarded | cells |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for name, r in shards:
        b = r.get("passB") or {}
        ts = r.get("written_task_strings") or {}
        arm, task = r.get("arm"), r.get("task")
        # duration_s was only recorded from it12 on, so earlier shards printed "? s" for a quantity that is
        # sitting in their own parquet. MEASURE it instead of reading a field: frames per episode / control_hz,
        # and say out loud whether the horizon is FIXED (it is -- uniq == 1 on all seven shards), because a
        # variable horizon would make episode length carry outcome information.
        EMB = _emb()
        import pandas as _pd, glob as _g
        try:
            _df = _pd.concat([_pd.read_parquet(f, columns=["episode_index"]) for f in
                              sorted(_g.glob(os.path.join(a.data, name, "ds", "data", "**", "*.parquet"),
                                             recursive=True))], ignore_index=True)
            _n = _df.groupby("episode_index").size()
            _hz = float(EMB[arm].control_hz) if arm in EMB else 0.0
            horizon = ("%.1f s (%d frames, FIXED)" % (_n.iloc[0] / _hz, _n.iloc[0]) if _n.nunique() == 1 and _hz
                       else "VARIES %d-%d frames" % (_n.min(), _n.max()))
        except Exception as _e:
            horizon = "unmeasured (%s)" % type(_e).__name__
        canon = f"{arm}-{task}"
        ep = b.get("parquet_episode_count")
        sc = os.path.join(a.data, name, "ds", "EPISODES.jsonl")
        nrows = sum(1 for _ in open(sc)) if os.path.exists(sc) else 0
        vg = vgs.get(name) or {}
        sidecar = (f"{nrows} rows, goals verified {vg.get('n_checked')}/{vg.get('n_checked')} to "
                   f"{vg.get('max_abs_delta'):.1e}" if nrows and vg.get("n_checked") else
                   (f"{nrows} rows, UNVERIFIED" if nrows else "**none**"))
        lb = (lbs.get(name) or {}).get("verdict") or "not run"
        # A variant shard priced on its OWN band (price_push --band-scale) gets its own file; only fall
        # back to the canonical arm cell when that does not exist, and the `cells` column says which.
        own = load(os.path.join(a.runs, f"price-push-{name}.json")) or load(
              os.path.join(a.runs, f"capture-radius-{name}.json")) or {}
        own_arm = (own.get("arms") or {}).get(arm)
        cell = own_arm or (pp.get(arm) if task == "push" else cr.get(arm))
        # margin_x is null in TWO opposite cases: no floor moves the cube (the criterion is maximally
        # sound, margin is infinite) and nothing was measured. Printing both as "UNDETERMINED" would have
        # understated venue18, whose floors displace 0.0 m -- so read the measured fields, not the ratio.
        if not cell:
            floor = "not priced"
        elif task != "push":
            floor = cell.get("verdict", "not priced")
        elif cell.get("false_successes_on_floors"):
            floor = "FALSE SUCCESSES %s" % cell["false_successes_on_floors"]
        elif cell.get("margin_x"):
            floor = "SOUND %sx" % cell["margin_x"]
        elif cell.get("floor_max_along_m") == 0.0:
            floor = "SOUND (floors displace 0.0 m)"
        else:
            floor = cell.get("verdict", "UNDETERMINED")
        # the canonical pricing file writes this flat, a --band-scale run nests it under "expert" --
        # reading only one spelling printed "n/a" for a shard whose ceiling HAD been measured (26/30).
        ceil = ((cell or {}).get("expert_would_be_scored_success")
                or ((cell or {}).get("expert") or {}).get("would_be_scored_success")) if task == "push" else None
        ex = (cell or {}).get("expert") or {}
        exmed = (ex.get("along_m") or {}).get("median") if ex else None
        pmin = (cell or {}).get("push_min_m") or (cell or {}).get("push_min")
        if task == "push" and ((cell or {}).get("push_min_exceeds_expert_median")
                               or (exmed and pmin and pmin > exmed)):
            ceil = f"**{ceil}** (threshold > expert median)"
        # SD-58 (SIMDATA): say IN THE TABLE whether a consumer can mistake a failure for a demonstration.
        kr = r["passA"]["keep_rate"]
        # A shard is successes-only or failures-only, and the shard's OWN report says which
        # (passA.keep_rate_is_for). Before it20 this script had no such column and its prose asserted
        # "failures are not published" as a constant -- which three negative splits later made false
        # while the generator kept printing it. Read the class; never assume it.
        is_neg = (r["passA"].get("keep_rate_is_for") == "failures")
        klass = "**NEGATIVE** (failures only)" if is_neg else "successes only"
        disc = int(round(ep / kr)) - ep if (ep and kr) else None
        if disc is None:
            fails = "unknown"
        elif is_neg:
            fails = f"{disc} SUCCESSES discarded (of ~{int(round(ep / kr))} attempts)"
        else:
            fails = f"{disc} failures discarded (of ~{int(round(ep / kr))} attempts)"
        classes.append((name, is_neg, ep))
        horizons.append((name, horizon))
        w("| `%s` | %s | %s | %s | %s / %s | %s | %s | %s | %s | %s | %s |" % (
            name, klass, ep, kr, r.get("band_scale", 1.0), horizon, sidecar, lb, floor,
            ceil or "n/a", fails, "own" if (name == canon or own_arm) else f"inherited from `{canon}`"))
    w("")
    # DERIVED, not typed: the old wording said "six canonical shards" and would have kept saying it after
    # four more shards existed. Count the measured horizons instead, and say plainly if any shard VARIES.
    hc = {}
    for _n, _h in horizons:
        hc[_h] = hc.get(_h, 0) + 1
    varies = [n for n, h in horizons if not h.endswith("FIXED)")]
    w("**%s of %d shards are FIXED-HORIZON**, measured from the parquet rather than taken from a field: %s."
      % (len(horizons) - len(varies), len(horizons),
         "; ".join("%s on %d" % (h, c) for h, c in sorted(hc.items(), key=lambda kv: -kv[1]))))
    if varies:
        w("")
        w("VARIABLE-LENGTH SHARDS (episode length can carry outcome information here): %s."
          % ", ".join("`%s`" % v for v in varies))
    w("")
    w("Two consequences of a fixed horizon, and the second is the one that bites.")
    w("")
    w("GOOD: episode length here carries ZERO information about outcome, so nothing in these shards lets a")
    w("head learn the shortcut SIMDATA measured in its own corpus (SD-64: failures run 2.3x longer than")
    w("successes, 120.6 vs 52.3 frames, because a timeout runs to the wall). Our episodes cannot leak that.")
    w("")
    w("HAZARD WHEN MIXED: if these shards are trained alongside a VARIABLE-length corpus, episode length")
    w("becomes a near-perfect source label (60 or 180 frames = us, anything else = them). Combined with a")
    w("corpus where length correlates with outcome, length-to-outcome becomes learnable ACROSS the mixture")
    w("even though neither corpus teaches it alone. Any lane mixing corpora should either truncate every")
    w("source to a common horizon or report the per-source length histogram next to its result.")
    w("")
    npos = sum(1 for _, neg, _ in classes if not neg)
    nneg = len(classes) - npos
    epos = sum(e or 0 for _, neg, e in classes if not neg)
    eneg = sum(e or 0 for _, neg, e in classes if neg)
    w("**Every shard is SINGLE-CLASS, and the `class` column says which.** %d shards / %d episodes are"
      % (npos, epos))
    w("successes only; %d shards / %d episodes are failures only (`*-FAIL`). No shard mixes the two, so a"
      % (nneg, eneg))
    w("consumer cannot silently train on a failure -- which is what SIMDATA's SD-58 found in another")
    w("corpus (604 of 3,109 episodes were failures with nothing marking which). On a negative shard `keep`")
    w("is the arm's FAILURE rate and the discard column counts the successes thrown away.")
    w("")
    w("READ `NEGATIVES.md` BEFORE TRAINING ON A `*-FAIL` SHARD: the three negative splits are not")
    w("interchangeable (the push ones are behavioural failures, the touch one is a tolerance boundary),")
    w("and the start-separability section below says how much of each label is decided before the arm")
    w("moves at all.")
    w("")
    w("`criterion floor` is the arm's OWN negative control (`push_sharp.py` for push, capture radius for")
    w("touch). UNDETERMINED means no floor on that arm moves the cube, so nothing bounds a false success")
    w("there. `validated ceiling` is the scripted expert's score under the same criterion; where the")
    w("threshold exceeds the expert's median, a rate on that arm is bounded by the ceiling, not the policy.")
    w("`cells` says whether the measurement cells shown later were measured on THIS shard or inherited from")
    w("the canonical one (a variant with a different band or episode length inherits them).")
    w("")
    w("`pass-A keep` is the expert's own success rate on freshly sampled cube poses: the shards are")
    w("successes-only, so it is the cost of a published episode, not a quality score. Replay")
    w("nondeterminism is the number of re-replayed episodes whose actions did not reproduce bit-exactly.")
    w("")
    w("## What a head trained on these can be tested for")
    w("")
    w("### Goal necessity (how much of the score requires reading the goal)")
    w("")
    w("`goal-aware` is the real expert planning to the true cube pose. `goal-blind` is the SAME code path")
    w("planning to the centre of the sampling band with the cube left where it is. `headroom` is the part")
    w("of the score a learner can only earn by reading the goal.")
    w("")
    w("| arm/task | band scale | goal-aware | goal-blind | headroom |")
    w("|---|---|---|---|---|")
    for k, v in sorted(nec.items()):
        if not v:
            continue
        for row in v["rows"]:
            w("| %s | %s | %s | %s | **%s** |" % (k, row["band_scale"], row["goal_aware"]["rate"],
                                                  row["goal_blind"]["rate"], row["headroom"]))
    w("")
    w("Widening the band is free and it is the lever: it does not move the expert's own success while it")
    w("cuts what a centre-aiming agent can get. `harvest.py --band-scale` sets it.")
    w("")
    w("### What the success label means (dwell, not graze)")
    w("")
    w("The criterion is min-over-episode, so a one-tick graze would qualify. It does not happen:")
    w("")
    w("| arm/task | cell | labelled | median dwell (steps) | dwell>=3 | dwell>=10 | ends in contact | grazes |")
    w("|---|---|---|---|---|---|---|---|")
    for k, v in sorted(dwl.items()):
        if not v:
            continue
        for cell, c in v["cells"].items():
            w("| %s | %s | %s/%s | %s | %s | %s | %s | %s |" % (
                k, cell, c["labelled_success"], v["episodes"], c["median_dwell_steps"],
                c["dwell_ge_3"], c["dwell_ge_10"], c["terminal_within_gap"],
                c["graze_only_dwell_1"]))
    w("")
    w("Dwell is in control steps at the arm's own `control_hz`, so it is not a duration comparable across")
    w("arms without dividing by hz.")
    w("")
    if pix:
        w("### How much of the image the goal controls (goal-only contrast, arm pinned)")
        w("")
        w("Rung-1 asks that episodes DIFFER at frame 0, not that the difference carries the goal, and the")
        w("two come apart. These numbers are whole-frame mean absolute difference on a 0-255 scale with")
        w("ONLY the cube moved, so they measure the image FRACTION the goal controls, not what a ViT")
        w("extracts from it.")
        w("")
        w("```json")
        w(json.dumps(pix, indent=1)[:1200])
        w("```")
        w("")
    ss = load(os.path.join(a.runs, "start-sep.json")) or {}
    if ss.get("pairs"):
        w("### How much of a failure label is decided at frame 0 (start separability)")
        w("")
        w("A success shard and its `-FAIL` sibling come from ONE seed stream, so a seed may appear in only")
        w("one of them (`seed overlap` is the integrity check: a seed in both would mean the success")
        w("criterion is nondeterministic). AUC below is a logistic regression on frame-0 information only,")
        w("5-fold stratified CV, scored on held-out folds; `goal` is where the cube was sampled and")
        w("`state` is the arm's jittered reset pose. `permuted` is the same code path with labels shuffled")
        w("(%d draws) and is the only reason to believe a number above chance." % ss.get("perms", 0))
        w("")
        w("| pair | n success | n fail | seed overlap | AUC goal | AUC state | AUC permuted (mean/max) |"
          " best single feature | all failures sampled inside a box holding this share of successes |")
        w("|---|---|---|---|---|---|---|---|---|")
        for r_ in ss["pairs"]:
            sing = {k: v for k, v in r_["single"].items() if not k.startswith("state[")}
            best = max(sing.items(), key=lambda kv: abs(kv[1] - 0.5))
            w("| `%s` vs `%s-FAIL` | %s | %s | %s | **%.3f** | %.3f | %.3f / %.3f | %s %.3f | **%.1f%%** |" % (
                r_["shard"], r_["shard"], r_["n_success"], r_["n_fail"], r_["seed_overlap"],
                r_["auc"]["goal"], r_["auc"]["state"], r_["auc_permuted_mean"]["goal"],
                r_["auc_permuted_max"]["goal"], best[0], best[1],
                100.0 * r_["fail_window"]["joint_box_success_fraction_inside"]))
        w("")
        w("The arm's own reset pose is at chance on every pair (AUC ~0.48-0.49), which is the negative")
        w("control for this measurement: the pipeline is not leaking episode identity. The CUBE POSE is")
        w("not at chance, so part of every failure label is a property of where the sampler put the cube,")
        w("not of what the policy did. A failure-aware objective trained on these splits must therefore")
        w("condition on the goal (or balance the sampled region) or it will learn the sampler.")
        w("")
    # Published repos are LISTED FROM THE HUB, not derived from shard names: a name I can spell is not
    # evidence a repo exists, and this doc's whole purpose is to be actionable by a consumer.
    w("## Published (private)")
    w("")
    try:
        from huggingface_hub import HfApi
        api = HfApi()
        repos = sorted(d.id for d in api.list_datasets(author="cagataydev",
                                                       search="strands-vla-rlenv"))
        if repos:
            w("Each shard is one private dataset repo with `ds/` at the root, tagged `v3.0`")
            w("(`LeRobotDataset` resolves `revision=CODEBASE_VERSION`, so the tag is what makes it")
            w("loadable at all):")
            w("")
            w("```python")
            w("from lerobot.datasets.lerobot_dataset import LeRobotDataset")
            w('ds = LeRobotDataset("%s")' % repos[0])
            w("```")
            w("")
            for r in repos:
                w("- `%s`" % r)
        else:
            w("No published repos found under cagataydev matching strands-vla-rlenv.")
    except Exception as exc:
        w("Could not list published repos: %s: %s" % (type(exc).__name__, exc))
    w("")
    w("## Limits that apply to every number above")
    w("")
    w("- These are EXPERT rollouts in MuJoCo, not policy rollouts and not a real arm. They bound what a")
    w("  head trained on the shards could demonstrate; they do not predict what one will.")
    w("- Necessity and dwell are n=40 per cell on one arm/task unless the table says otherwise.")
    w("- A shard being clean says nothing about whether the task is hard enough to be worth training on.")
    open(a.out, "w").write("\n".join(L) + "\n")
    print(json.dumps({"shards": len(shards), "necessity": len(nec), "dwell": len(dwl),
                      "lines": len(L), "out": a.out}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
